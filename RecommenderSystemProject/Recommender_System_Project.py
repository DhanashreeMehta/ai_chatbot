# Step 4: Collaborative filtering
# Full hybrid system builds a user-item matrix
# and calculates similarity between users using a centered cosine method,
# similar to Pearson correlation (Sarwar et al., 2001).

user_item = df.pivot_table(index="userId", columns="movieId", values="rating")

def user_similarity(user_id):
    """Calculate similarity between the given user and all other users."""
    matrix = user_item.fillna(0)
    if user_id not in matrix.index:
        return pd.Series(dtype=float)
    centered = matrix.sub(matrix.mean(axis=1), axis=0)
    sims = cosine_similarity(centered)
    sims_df = pd.DataFrame(sims, index=matrix.index, columns=matrix.index)
    return sims_df[user_id].drop(user_id)

def collaborative_recommend(user_id, top_n=5):
    """Predict ratings for movies a user has not seen, using similar users."""
    if user_id not in user_item.index:
        return pd.DataFrame()

    sims = user_similarity(user_id)
    if sims.empty or sims.abs().sum() == 0:
        return pd.DataFrame()

    user_ratings = user_item.loc[user_id]
    unseen = user_ratings[user_ratings.isna()].index

    predictions = {}
    for movie_id in unseen:
        others = user_item[movie_id].dropna()
        weights = sims.loc[others.index]
        if weights.abs().sum() == 0:
            continue
        pred = np.dot(others, weights) / weights.abs().sum()
        predictions[movie_id] = pred

    if not predictions:
        return pd.DataFrame()

    pred_series = pd.Series(predictions).sort_values(ascending=False).head(top_n)
    out = movies.set_index("movieId").loc[pred_series.index].reset_index()
    out["collab_score"] = pred_series.values
    return out

