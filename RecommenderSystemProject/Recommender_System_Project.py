# Step 5: Hybrid recommendation function
# This blends content based and collaborative filtering scores together
# using an adjustable weight (alpha), following the hybrid approach
# described by Burke (2002). It also handles the cold start problem for
# new users by falling back to popularity based recommendations.

def hybrid_recommend(user_id, seed_movie_id=None, top_n=5, alpha=0.6):
    collab = collaborative_recommend(user_id, top_n=top_n * 2)

    if collab.empty:
        # Cold start fallback: recommend based on overall popularity
        popularity = df.groupby("movieId")["rating"].mean().sort_values(ascending=False)
        top_movies = movies.set_index("movieId").loc[popularity.index[:top_n]].reset_index()
        top_movies["hybrid_score"] = popularity.values[:top_n]
        return top_movies

    # Fix: rename the 'index' column back to 'movieId' if it exists in collab
    if "index" in collab.columns and "movieId" not in collab.columns:
        collab = collab.rename(columns={"index": "movieId"})

    if seed_movie_id is None:
        rated = user_item.loc[user_id].dropna()
        seed_movie_id = rated.idxmax() if not rated.empty else movies.iloc[0]["movieId"]

    content = content_based_recommend(seed_movie_id, top_n=top_n * 2)

    merged = pd.merge(collab, content, on=["movieId", "title", "genres"], how="outer")
    merged["collab_score"] = merged["collab_score"].fillna(0)
    merged["content_score"] = merged["content_score"].fillna(0)
    merged["hybrid_score"] = alpha * merged["collab_score"] + (1 - alpha) * merged["content_score"]

    merged = merged.sort_values("hybrid_score", ascending=False).head(top_n)
    return merged[["movieId", "title", "genres", "hybrid_score"]]

