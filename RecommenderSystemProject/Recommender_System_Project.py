# Step 3: Content based filtering
# This section builds a TF-IDF matrix from movie genres and calculates
# cosine similarity between movies. This approach is based on the common
# tutorial pattern used for beginner movie recommendation projects
# (Banik, 2018; Kaggle, n.d.), credited fully in the report references.

movies = df[["movieId", "title", "genres"]].drop_duplicates(subset="movieId").reset_index(drop=True)

tfidf = TfidfVectorizer(token_pattern=r"[A-Za-z]+")
genre_matrix = tfidf.fit_transform(movies["genres"].str.replace("|", " "))

content_sim = cosine_similarity(genre_matrix)
movie_index = pd.Series(movies.index, index=movies["movieId"])

def content_based_recommend(movie_id, top_n=5):
    """Return the most similar movies to a given movie, based on genre similarity."""
    if movie_id not in movie_index:
        return pd.DataFrame()
    idx = movie_index[movie_id]
    sims = list(enumerate(content_sim[idx]))
    sims = sorted(sims, key=lambda x: x[1], reverse=True)
    sims = [s for s in sims if s[0] != idx][:top_n]
    result_idx = [s[0] for s in sims]
    scores = [s[1] for s in sims]
    out = movies.iloc[result_idx].copy()
    out["content_score"] = scores
    return out

