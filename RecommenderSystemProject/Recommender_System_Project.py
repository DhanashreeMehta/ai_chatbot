# Step 6: Add a new rating and rebuild models
# This allows a user to rate a movie during the session, after which the
# data and models are rebuilt so the new rating is reflected immediately.

def add_rating(user_id, movie_id, title, genres, rating):
    global df, movies, user_item, content_sim, movie_index, genre_matrix

    new_row = {"userId": user_id, "movieId": movie_id, "title": title, "genres": genres, "rating": rating}
    df = pd.concat([df, pd.DataFrame([new_row])], ignore_index=True)

    movies = df[["movieId", "title", "genres"]].drop_duplicates(subset="movieId").reset_index(drop=True)
    genre_matrix = tfidf.fit_transform(movies["genres"].str.replace("|", " "))
    content_sim = cosine_similarity(genre_matrix)
    movie_index = pd.Series(movies.index, index=movies["movieId"])

    user_item = df.pivot_table(index="userId", columns="movieId", values="rating")
    print(f"Rating recorded: user {user_id} rated '{title}' as {rating}")

# Step 7: Conversational interface
# This runs a simple text based chatbot loop so the user interacts with
# the system by typing commands instead of using a graphical interface.

def print_movies(result_df):
    if result_df.empty:
        print("No recommendations available.")
        return
    for _, row in result_df.iterrows():
        score_col = [c for c in result_df.columns if "score" in c]
        score = f" (score: {row[score_col[0]]:.2f})" if score_col else ""
        print(f"  - {row['title']} [{row['genres']}]{score}")

